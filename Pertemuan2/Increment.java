package Pertemuan2;

public class Increment {
   public static void main(String[] args) {
        int x = 12;
        System.out.println("Nilai awal x: " + x);
        System.out.println("Pre-increment (++x): " + (++x)); // Nilai ditambah sebelum dicetak
        System.out.println("Post-increment (x++): " + (x++)); // Dicetak dulu baru nilainya ditambah
        System.out.println("Nilai akhir x: " + x);
    } 
}
