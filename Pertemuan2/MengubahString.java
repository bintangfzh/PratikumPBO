package Pertemuan2;

public class MengubahString {
    public static void main(String[] args) {
        String a = "Saya Belajar Java";
        String b = "Saya Belajar Java";
        
        System.out.println("String a awal : " + a);
        System.out.println("Menjadi kecil : " + a.toLowerCase());
        
        System.out.println("-----------------------------------");
        
        System.out.println("String b awal : " + b);
        System.out.println("Menjadi BESAR : " + b.toUpperCase());
    }
}
