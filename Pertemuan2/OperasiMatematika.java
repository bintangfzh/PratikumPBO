package Pertemuan2;

public class OperasiMatematika {
    public static void main(String[] args) {
        double x = 22;
        double y = 33;
        
        System.out.println("Nilai x = " + x);
        System.out.println("Nilai y = " + y);
        System.out.println("Hasil dari Penjumlahan (x + y) = " + (x + y));
        System.out.println("Hasil dari Pengurangan (x - y) = " + (x - y));
        System.out.println("Hasil dari Perkalian   (x * y) = " + (x * y));
        System.out.println("Hasil dari Pembagian   (x / y) = " + (x / y));
    }
}
