package pertemuan5;

public class No_8 {
    public static void main(String[] args) {
        int[] nilaiArray = {80, 85, 90, 75, 95};

        System.out.println("Menampilkan semua nilai dalam variabel array menggunakan for-each:");

        for (int nilai : nilaiArray) {
            System.out.print(nilai + " ");
        }
        
        System.out.println();
    }
}
